type TransKey = keyof typeof translations.en;

interface I18nContextProps {
    lang: Lang;
    setLang: (lang: Lang) => void;
    t: (key: TransKey, ...args: (string | number)[]) => string;
}

const I18nContext = createContext<I18nContextProps | undefined>(undefined);

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
    const [lang, setLang] = useState<Lang>(() => {
        return (localStorage.getItem('mcd_lang') as Lang) || 'ja';
    });

    useEffect(() => {
        localStorage.setItem('mcd_lang', lang);
    }, [lang]);

    const t = (key: TransKey, ...args: (string | number)[]) => {
        let str = translations[lang][key] || translations.en[key] || key;
        args.forEach((arg, i) => {
            str = str.replace(`{${i}}`, String(arg));
        });
        return str;
    };

    return (
        <I18nContext.Provider value={{ lang, setLang, t }}>
            {children}
        </I18nContext.Provider>
    );
};

export const useI18n = () => {
    const context = useContext(I18nContext);
    if (!context) throw new Error("useI18n must be used within LanguageProvider");
    return context;
};
